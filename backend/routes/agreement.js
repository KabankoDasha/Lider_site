const router = require('express').Router();
const auth = require('../middleware/auth');
const adminOnly = require('../middleware/adminOnly');
const { Agreement } = require('../models/agreement');
const puppeteer = require('puppeteer');

// Получить свой договор
router.get('/my', auth, async (req, res) => {
  try {
    const agreement = await Agreement.findByUserId(req.user.id);
    res.json(agreement || null);
  } catch (err) {
    console.error(err);
    res.status(500).json({ message: 'Ошибка сервера' });
  }
});

// Сохранить / обновить договор
router.post('/my', auth, async (req, res) => {
  try {
    const userId = req.user.id;
    const data = req.body;
    data.status = data.status || 'draft';
    const agreement = await Agreement.createOrUpdate(userId, data);
    res.json(agreement);
  } catch (err) {
    console.error(err);
    res.status(500).json({ message: 'Ошибка сервера' });
  }
});

// Обновить курс договора (для пользователя)
router.patch('/:id', auth, async (req, res) => {
  const { id } = req.params;
  const { course } = req.body;
  if (!course) return res.status(400).json({ message: 'Курс обязателен' });

  const agreement = await Agreement.findById(id);
  if (!agreement) return res.status(404).json({ message: 'Договор не найден' });
  if (agreement.user_id !== req.user.id && req.user.role !== 'admin') {
    return res.status(403).json({ message: 'Доступ запрещён' });
  }

  const updated = await Agreement.updateCourse(id, course);
  res.json(updated);
});

// Админ: все договоры
router.get('/admin', auth, adminOnly, async (req, res) => {
  try {
    const list = await Agreement.findAllAdmin();
    res.json(list);
  } catch (err) {
    console.error(err);
    res.status(500).json({ message: 'Ошибка сервера' });
  }
});

// Генерация PDF
router.get('/:id/pdf', auth, async (req, res) => {
  try {
    const agreement = await Agreement.findById(req.params.id);
    if (!agreement) return res.status(404).json({ message: 'Договор не найден' });

    if (req.user.role !== 'admin' && agreement.user_id !== req.user.id) {
      return res.status(403).json({ message: 'Доступ запрещён' });
    }

    // Формируем инициалы заказчика
    const shortName = agreement.full_name
      ? agreement.full_name.split(' ').map((s, i) => i === 0 ? s : s.charAt(0) + '.').join(' ')
      : '';

    const html = buildAgreementHtml(agreement, shortName);

    const browser = await puppeteer.launch({ headless: true, args: ['--no-sandbox'] });
    const page = await browser.newPage();
    await page.setContent(html, { waitUntil: 'networkidle0' });
    const pdfBuffer = await page.pdf({ format: 'A4', printBackground: true });
    await browser.close();

    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', `inline; filename="dogovor-${agreement.id}.pdf"`);
    res.send(pdfBuffer);
  } catch (err) {
    console.error(err);
    res.status(500).json({ message: 'Ошибка генерации PDF' });
  }
});

